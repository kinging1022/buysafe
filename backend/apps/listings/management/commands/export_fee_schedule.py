"""Writes the fee tiers and the landing page's worked examples, computed by
calculate_fee(), to frontend/src/config/fees.generated.json. The landing page
is prerendered, so it reads this file at build time instead of doing fee maths.

Run after changing the tiers:  python manage.py export_fee_schedule
A test fails if the committed file no longer matches the backend.
"""

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from apps.listings.fees import calculate_fee, fee_schedule

OUTPUT = Path(settings.BASE_DIR).parent / "frontend" / "src" / "config" / "fees.generated.json"

# Prices the landing page works through: the Fees section, How it works
# step 04 (the fridge) and the vendor payout card (the sofa).
EXAMPLES = {"fees_section": 50_000, "fridge": 185_000, "sofa": 120_000}


def build():
    return {
        "_note": "Generated by `python manage.py export_fee_schedule`. Do not edit.",
        **fee_schedule(),
        "examples": {name: calculate_fee(price).as_dict() for name, price in EXAMPLES.items()},
    }


def render():
    return json.dumps(build(), ensure_ascii=False, indent=2) + "\n"


class Command(BaseCommand):
    help = "Write the fee schedule and landing examples for the frontend build."

    def handle(self, *args, **options):
        OUTPUT.write_text(render(), encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"Wrote {OUTPUT}"))
